/**
 * Точка входа. Сам по себе файл пустой: он только решает, когда
 * запускать основной код сайта (src/app.js).
 *
 * Зачем так. Основной код — это примерно 170 КБ: Lenis, Matter.js и
 * инициализация всех секций разом. Пока браузер всё это разбирает и
 * выполняет, главный поток занят на сотни миллисекунд, и всё, что в это
 * время движется, замирает. Поэтому его нельзя запускать, пока кисть
 * прелоадера бежит по экрану.
 *
 * Но и после прелоадера нельзя: тогда логотип, стикеры, плеер и прочее,
 * что создаёт JS, появляется на уже открытой странице.
 *
 * Поэтому с прелоадером-мазком код запускается ровно в тот момент, когда
 * экран закрыт сплошной заливкой и ничего не движется (событие
 * preloader-covered). Когда всё создано, отвечаем событием app-ready —
 * мазок ждёт его и только потом открывает сайт. Картинки и шрифты при
 * этом грузятся как обычно, они от этого файла не зависят.
 */

let booting = null;
const boot = () => {
  booting ||= import('./app.js').then(() => window.dispatchEvent(new Event('app-ready')));
  return booting;
};

if (window.PRELOADER === 'stroke') {
  window.addEventListener('preloader-covered', boot, { once: true });
  // Страховка: если прелоадер почему-то не дошёл до заливки или не доиграл —
  // всё равно запускаем
  window.addEventListener('preloader-done', boot, { once: true });
  setTimeout(boot, 6000);
  // Мазок мог дойти до заливки раньше, чем загрузился этот файл
  if (window.__preloaderState) boot();
} else {
  boot();
}
