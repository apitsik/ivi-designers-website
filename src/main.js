/**
 * Точка входа. Сам по себе файл пустой: он только решает, когда
 * запускать основной код сайта (src/app.js).
 *
 * Зачем так. Основной код — это примерно 170 КБ: Lenis, Matter.js и
 * инициализация всех секций разом. Пока браузер всё это разбирает и
 * выполняет, главный поток занят, и анимация прелоадера замирает —
 * в записи было видно, как кадры слипаются, а закрашивание прыгает
 * с трети экрана сразу на весь. Замер показал провал до 583 мс на
 * один кадр; без основного кода худший кадр — 100 мс.
 *
 * Поэтому с прелоадером-мазком основной код запускается после него:
 * во время прелоадера на странице всё равно нечего нажимать, зато
 * мазок идёт ровно. Картинки и шрифты при этом грузятся как обычно,
 * они от этого файла не зависят.
 */

const boot = () => import('./app.js');

if (window.PRELOADER === 'stroke') {
  window.addEventListener('preloader-done', boot, { once: true });
  // Страховка: если прелоадер почему-то не доиграл — всё равно запускаем
  setTimeout(boot, 4000);
} else {
  boot();
}
